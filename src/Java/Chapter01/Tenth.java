package Java.Chapter01;

public class Tenth {
    public static void main(String []args){
        //Java.Chapter01.Tenth as Logical Operator
        //Java.Chapter01.Tenth as Logical Example
        int age = 25;
        boolean hasID = true;
        System.out.println(age > 18 && hasID); // true
        System.out.println(age > 30 || hasID); // true
        System.out.println (!(age > 18)); // false

    }
}
