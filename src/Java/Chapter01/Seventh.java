package Java.Chapter01;

public class Seventh {
    public static void main(String[]args){
       //Unary Operators as Java.Chapter01.Seventh
       int x = 5;
       System.out.println("Pre-increment:" + (++x));//6
        System.out.println("Post-increment:" + (x--));//6
        System.out.println("Value after post-decrement:"+x);//5
        System.out.println("Logical NOT: "+(!true));//false

    }
}
