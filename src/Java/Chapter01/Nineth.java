package Java.Chapter01;

public class Nineth{
    public static void main(String []args){
        //Relational Operator as Java.Chapter01.Nineth
       // public class Relational Example

        int a = 10, b = 20;
        System.out.println(a == b);//false
        System.out.println(a!=b); // true
        System.out.println(a>b); // false
        System.out.println(a<b); // true
        System.out.println(a>=b); // false
        System.out.println(a<=b); // true

    }
}
